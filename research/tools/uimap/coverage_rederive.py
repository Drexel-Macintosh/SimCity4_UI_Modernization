def _run_injection(name, patcher, describe):
    """Run main() with a deliberate defect injected; the net must REJECT it."""
    print()
    print("#" * 74)
    print("# SELFTEST CASE: %s" % name)
    for ln in describe:
        print("#   %s" % ln)
    print("# EXPECTED RESULT: this run must FAIL (rc != 0).")
    print("#" * 74)
    print()
    undo = patcher()
    try:
        rc = main()
    finally:
        undo()
    print()
    if rc == 0:
        print("# >>> SELFTEST CASE FAILED: broken instrument ACCEPTED (rc=0). <<<")
        return 1
    print("# >>> SELFTEST CASE PASSED: rejected with rc=%d. <<<" % rc)
    return 0


def selftest():
    """NEGATIVE CONTROL for the regression net itself.

    Re-injects BOTH known #99 defects, one at a time, and demands that main()
    FAILS on each. A regression net that has never been seen to fail is not
    evidence that it works - and the corpus-filter defect (case 2) is one that
    the net as shipped on 2026-08-03 morning did NOT catch, because EXPECT had
    been frozen to the post-drop numbers.
    """
    results = []

    # ---- case 1: the original 'break at first <LEGACY>' ----
    def patch_first_root_only():
        g = globals()
        orig = g["parse_script"]

        def broken(path):
            p = orig(path)
            if p:
                p["roots"] = p["roots"][:1]     # <-- the old `break`
            return p
        g["parse_script"] = broken
        return lambda: g.__setitem__("parse_script", orig)

    results.append(_run_injection(
        "1/4 - numerator: keep only the FIRST depth-0 root per file",
        patch_first_root_only,
        ["This is the defect named in coverage-matrix.md section 3.",
         "It silently collapsed 21 multi-root scripts to one root each."]))

    # ---- case 2: the corpus filter that was documented-as-fixed but was not ----
    def patch_exact_banner_filter():
        g = globals()
        orig_banner = g["banner_ok"]
        orig_content = g["content_ok"]

        # Restore the exact-string, BOM-blind, case-sensitive test AND make the
        # content classifier agree with it, i.e. reproduce a SILENT drop rather
        # than a classifier disagreement. This is the harder case: it is what
        # the tool actually did, and it must still be caught.
        def broken_banner(text):
            return text.lstrip().startswith(BANNER)
        g["banner_ok"] = broken_banner
        g["content_ok"] = broken_banner
        return lambda: (g.__setitem__("banner_ok", orig_banner),
                        g.__setitem__("content_ok", orig_content))

    results.append(_run_injection(
        "2/4 - denominator: exact-string BOM-blind banner filter (silent drop)",
        patch_exact_banner_filter,
        ["Drops 1 UTF-8-BOM'd game script and 7 '# Generated by UIEditor'",
         "plugin scripts = 8 depth-0 roots. Both classifiers are broken the",
         "SAME way on purpose, so accounting() sees no disagreement and only",
         "the EXPECT totals can catch it. If this case passes, EXPECT has",
         "been re-frozen to a post-drop corpus again."]))

    # ---- case 3: a defect INSIDE the shared enumerator ----
    # The pre-fix accounting() could not see this: it re-called the same pure
    # function and compared it with itself. Measured before the fix, with 48 of
    # 338 roots gone, it still printed "290 carried / 290 fresh ... [OK ]".
    def patch_enumerator_first_root_only():
        g = globals()
        orig = g["enumerate_roots"]

        def broken(text):
            roots, d, md = orig(text)
            return roots[:1], d, md
        g["enumerate_roots"] = broken
        return lambda: g.__setitem__("enumerate_roots", orig)

    results.append(_run_injection(
        "3/4 - ROOT CONSERVATION must catch a drop INSIDE enumerate_roots",
        patch_enumerator_first_root_only,
        ["Same drop as case 1, but injected one level lower - in the enumerator",
         "the census and CLASSIFIER B share. Only a parser that shares no code",
         "with it (enumerate_roots_streamwise) can contradict it. Look for",
         "'[FAIL] ROOT CONSERVATION' in the run below; if that line is missing",
         "the reconciliation has gone back to comparing a function to itself."]))

    # ---- case 4: the corpus enumeration silently losing a directory ----
    # script_files() returns [] for a directory that does not exist. all_files
    # and records both shrink together, so no partition arithmetic can see it.
    def patch_drop_plugin_dir():
        g = globals()
        orig = g["script_files"]

        def broken(d):
            if d == SCRIPTS_PLUGINS:
                return []          # <-- the `if not os.path.isdir(d)` path
            return orig(d)
        g["script_files"] = broken
        return lambda: g.__setitem__("script_files", orig)

    results.append(_run_injection(
        "4/4 - FILE CONSERVATION must catch a silently vanished source dir",
        patch_drop_plugin_dir,
        ["script_files() returns [] for a missing directory, so the census and",
         "its own verdict partition agree on a truncated corpus. Only an",
         "enumeration that does not derive from script_files() - the recursive",
         "walk - can contradict it. Look for '[FAIL] FILE CONSERVATION'."]))

    print()
    print("#" * 74)
    if any(results):
        print("# SELFTEST FAILED: %d of %d injected defects were ACCEPTED."
              % (sum(results), len(results)))
        print("# The net does NOT catch #99. Fix EXPECT / accounting / controls.")
        print("#" * 74)
        return 1
    print("# SELFTEST PASSED: all %d injected defects were rejected." % len(results))
    print("# (Ignore the FAIL banners above - they are the point of this mode.)")
    print("#" * 74)
    return 0


