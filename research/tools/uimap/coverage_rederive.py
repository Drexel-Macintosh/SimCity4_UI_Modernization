def cpp_id_list(text, name):
    """Extract the hex ids out of `const uint32_t <name>[] = { ... };`."""
    i = text.find(name + "[]")
    if i < 0:
        return None, None
    j = text.find("{", i)
    # brace-match
    depth = 0
    k = j
    while k < len(text):
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    body = text[j:k]
    # strip // and /* */ comments so commented-out ids do not count
    body_nc = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body_nc = re.sub(r"//[^\n]*", "", body_nc)
    ids = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{6,8})\b", body_nc)]
    line = text[:i].count("\n") + 1
    return ids, line


